DECLARE @i INT = 1;
WHILE @i <= 1100
BEGIN

----------CURSO POR USUARIO VALIDO

DECLARE @id_curso_por_usuario INT;
SELECT @id_curso_por_usuario = id_curso_por_usuario
FROM (
SELECT
id_curso_por_usuario,
ROW_NUMBER() OVER (
ORDER BY id_curso_por_usuario
) AS fila
FROM dbo.curso_por_usuario
) c
WHERE fila = ((@i - 1) % 1100) + 1;

-----EJERCICIO VALIDO
----8876 ejercicios existentes


DECLARE @id_ejercicio INT =
((@i * 7) % 8876) + 1;


-----FECHA COHERENTE
----fecha con hora real, nunca medianoche

DECLARE @fecha DATETIME =
DATEADD(
MINUTE,
(@i * 13) % 1440,
DATEADD(
DAY,
@i % 120,
'2026-01-01 08:00:00'
)
);

----RESULTADO DEL EJERCICIO



DECLARE @correcto BIT;


-----80% correctos aprox


IF (@i % 5 = 0)
SET @correcto = 0;
ELSE
SET @correcto = 1;


----XP GANADO


DECLARE @xp_ganado INT;


/*
si falla → 0 XP
si acierta → XP variable
*/


IF @correcto = 0
SET @xp_ganado = 0;
ELSE
SET @xp_ganado =
((@i % 5) + 1) * 5;



----------INSERT


INSERT INTO dbo.ejercicio_realizado
(
id_ejercicio_realizado,
id_curso_por_usuario,
id_ejercicio,
fecha,
correcto,
xp_ganado
)
VALUES
(
@i,
@id_curso_por_usuario,
@id_ejercicio,
@fecha,
@correcto,
@xp_ganado
);


SET @i = @i + 1;

END; 



UPDATE er
SET er.xp_ganado = CASE 
    WHEN er.correcto = 1 THEN e.xp_otorgado
    ELSE 0 
END
FROM ejercicio_realizado er
INNER JOIN ejercicio e ON er.id_ejercicio = e.id_ejercicio;


