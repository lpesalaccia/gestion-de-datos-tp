-- Update 1: corregir xp_acumulado_grupo
UPDATE grupo_competencia_por_usuario
SET xp_acumulado_grupo = (
    SELECT ISNULL(SUM(er.xp_ganado), 0)
    FROM ejercicio_realizado er
        INNER JOIN curso_por_usuario cpu
            ON er.id_curso_por_usuario = cpu.id_curso_por_usuario
    WHERE cpu.id_usuario = grupo_competencia_por_usuario.id_usuario
)
GO

-- Update 2: recalcular puestos en base al XP dentro de cada grupo
UPDATE grupo_competencia_por_usuario
SET puesto = (
    SELECT COUNT(*) + 1
    FROM grupo_competencia_por_usuario gcpu2
    WHERE gcpu2.id_grupo_competencia = grupo_competencia_por_usuario.id_grupo_competencia
    AND gcpu2.xp_acumulado_grupo > grupo_competencia_por_usuario.xp_acumulado_grupo
    AND gcpu2.fecha_baja IS NULL
)
WHERE fecha_baja IS NULL
GO

